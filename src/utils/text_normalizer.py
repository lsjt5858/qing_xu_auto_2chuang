_OPENCC_T2S = OpenCC("t2s") if OpenCC else None


def _fallback_t2s(text: str) -> str:
    normalized = text
    for trad, simp in _PHRASE_MAP_T2S.items():
        normalized = normalized.replace(trad, simp)
    return normalized.translate(_CHAR_MAP_T2S)


def normalize_chinese_text(text: str, *, target_script: str = "simplified") -> str:
    if not text:
        return text
    if target_script != "simplified":
        raise ValueError(f"Unsupported target_script: {target_script}")
    if _OPENCC_T2S is not None:
        return _OPENCC_T2S.convert(text)
    return _fallback_t2s(text)
