VIDEO_EXTENSIONS = {".mp4", ".mov", ".m4v", ".avi", ".mkv", ".webm"}
AUDIO_EXTENSIONS = {".mp3", ".wav", ".m4a", ".aac", ".mov"}


def new_id() -> str:
    return str(uuid.uuid4()).upper()


def to_us(seconds: float) -> int:
    return max(0, int(round(float(seconds) * 1_000_000)))


def now_us() -> int:
    return int(datetime.now().timestamp() * 1_000_000)


def safe_draft_name(name: str) -> str:
    name = re.sub(r"[/:\\\0]", "_", name).strip()
    name = re.sub(r"\s+", " ", name)
    return name[:80] or f"chai_export_{datetime.now():%Y%m%d_%H%M%S}"


def run_json(cmd: list[str]) -> dict[str, Any]:
    result = subprocess.run(cmd, check=True, capture_output=True, text=True)
    return json.loads(result.stdout)


def probe_media(path: Path) -> dict[str, Any]:
    data = run_json(
        [
            "ffprobe",
            "-v",
            "error",
            "-show_streams",
            "-show_format",
            "-print_format",
            "json",
            str(path),
        ]
    )
    streams = data.get("streams", [])
    video_stream = next((s for s in streams if s.get("codec_type") == "video"), None)
    audio_stream = next((s for s in streams if s.get("codec_type") == "audio"), None)

    duration = None
    for source in (video_stream, audio_stream, data.get("format", {})):
        if source and source.get("duration") not in (None, "N/A"):
            duration = float(source["duration"])
            break

    return {
        "duration": to_us(duration or 0),
        "width": int(video_stream.get("width", 0)) if video_stream else 0,
        "height": int(video_stream.get("height", 0)) if video_stream else 0,
        "has_audio": audio_stream is not None,
    }


def load_json(path: Path, default: Any = None) -> Any:
    if not path.exists():
        return default
    with path.open("r", encoding="utf-8") as f:
        return json.load(f)


def dump_json(path: Path, data: Any, *, pretty: bool = True) -> None:
    with path.open("w", encoding="utf-8") as f:
        if pretty:
            json.dump(data, f, ensure_ascii=False, indent=4)
        else:
            json.dump(data, f, ensure_ascii=False, separators=(",", ":"))


def copy_template(template_dir: Path, draft_dir: Path) -> None:
    if not template_dir.exists():
        raise FileNotFoundError(f"Template directory not found: {template_dir}")
    if draft_dir.exists():
        raise FileExistsError(f"Draft already exists: {draft_dir}")
    shutil.copytree(template_dir, draft_dir)
    for subdir in ("video", "audio", "Resources", "common_attachment", "Timelines"):
        (draft_dir / subdir).mkdir(exist_ok=True)


def discover_output(output_dir: Path) -> tuple[dict[str, Any], list[Path], Path | None, list[dict[str, Any]]]:
    if not output_dir.exists():
        raise FileNotFoundError(f"Output directory not found: {output_dir}")

    report = load_json(output_dir / "report.json", {})
    scenes_dir = output_dir / "scenes"
    scene_files = sorted(
        p for p in scenes_dir.glob("*") if p.suffix.lower() in VIDEO_EXTENSIONS
    )
    if not scene_files and (output_dir / "video_no_subtitles.mp4").exists():
        scene_files = [output_dir / "video_no_subtitles.mp4"]
    if not scene_files:
        raise FileNotFoundError(f"No scene videos found in: {scenes_dir}")

    audio_path = output_dir / "audio.mp3"
    if not audio_path.exists():
        audio_candidates = sorted(
            p for p in output_dir.glob("*") if p.suffix.lower() in AUDIO_EXTENSIONS
        )
        audio_path = audio_candidates[0] if audio_candidates else None

    transcript = load_json(output_dir / "transcript_detailed.json", None)
    if transcript is None:
        transcript = report.get("transcript_segments", [])

    return report, scene_files, audio_path, transcript or []


