def try_generate_cover(draft_dir: Path, first_video: Path) -> None:
    cover = draft_dir / "draft_cover.jpg"
    try:
        subprocess.run(
            [
                "ffmpeg",
                "-y",
                "-v",
                "error",
                "-i",
                str(first_video),
                "-frames:v",
                "1",
                str(cover),
            ],
            check=True,
        )
    except Exception:
        # The template already contains a fallback cover in most cases.
        pass


def build_draft(
    output_dir: Path,
    draft_root: Path,
    template_dir: Path,
    draft_name: str | None = None,
) -> Path:
    report, scene_files, audio_path, transcript = discover_output(output_dir)
    title = report.get("video_name") or output_dir.name
    draft_name = safe_draft_name(draft_name or f"chai_{title}_{datetime.now():%H%M%S}")
    draft_dir = draft_root / draft_name

    copy_template(template_dir, draft_dir)

    draft_id = new_id()
    video_dir = draft_dir / "video"
    audio_dir = draft_dir / "audio"

    base_info = load_json(template_dir / "draft_info.json")
    materials = {key: [] for key in base_info.get("materials", {}).keys()}
    for extra_key in ("common_mask", "audio_pannings", "audio_pitch_shifts", "hsl_curves",
                      "manual_beautys", "placeholder_infos", "video_radius",
                      "video_shadows", "video_strokes"):
        materials.setdefault(extra_key, [])

    video_segments: list[dict[str, Any]] = []
    timeline_pos = 0
    canvas_width = 1920
    canvas_height = 1080

    report_scenes = report.get("scenes") or []
    for index, src in enumerate(scene_files, start=1):
        probe = probe_media(src)
        scene_duration = 0
        if index <= len(report_scenes):
            scene_duration = to_us(report_scenes[index - 1].get("duration", 0))
        duration = scene_duration or probe["duration"]
        if duration <= 0:
            continue

        if probe["width"] and probe["height"]:
            canvas_width, canvas_height = probe["width"], probe["height"]

        target_name = f"Scene-{index:03d}{src.suffix.lower()}"
        target_path = video_dir / target_name
        shutil.copy2(src, target_path)

        material_id = new_id()
        speed_id = new_id()
        materials["videos"].append(
            make_video_material(
                material_id,
                str(target_path),
                target_name,
                duration,
                probe["width"] or canvas_width,
                probe["height"] or canvas_height,
            )
        )
        materials["speeds"].append(make_speed(speed_id))
        video_segments.append(
            make_visual_segment(
                new_id(),
                material_id,
                timeline_pos,
                duration,
                render_index=0,
                volume=0.0,
                speed_id=speed_id,
                source_timerange={"start": 0, "duration": duration},
            )
        )
        timeline_pos += duration

    audio_segments: list[dict[str, Any]] = []
    if audio_path and audio_path.exists():
        audio_probe = probe_media(audio_path)
        audio_duration = min(audio_probe["duration"] or timeline_pos, timeline_pos)
        target_audio_name = f"audio{audio_path.suffix.lower()}"
        target_audio_path = audio_dir / target_audio_name
        shutil.copy2(audio_path, target_audio_path)

        audio_material_id = new_id()
        audio_speed_id = new_id()
        materials["audios"].append(
            make_audio_material(
                audio_material_id,
                str(target_audio_path),
                target_audio_name,
                audio_duration,
            )
        )
        materials["speeds"].append(make_speed(audio_speed_id))
        audio_segments.append(
            make_audio_segment(new_id(), audio_material_id, 0, audio_duration, audio_speed_id)
        )

    text_segments: list[dict[str, Any]] = []
    fixed_width = int(canvas_width * 0.7) if canvas_width >= canvas_height else int(canvas_width * 0.82)
    for item in transcript:
        text = str(item.get("text", "")).strip()
        if not text:
            continue
        start = to_us(item.get("start", 0))
        end = to_us(item.get("end", 0))
        duration = max(0, end - start)
        if duration <= 0 or start >= timeline_pos:
            continue
        duration = min(duration, timeline_pos - start)

        material_id = new_id()
        materials["texts"].append(make_text_material(material_id, text, fixed_width=fixed_width))
        text_segments.append(
            make_visual_segment(
                new_id(),
                material_id,
                start,
                duration,
                render_index=15000,
                volume=1.0,
                speed_id=None,
                source_timerange=None,
                transform_y=-0.78,
            )
        )

    tracks = [make_track("video", "主视频", video_segments)]
    if audio_segments:
        tracks.append(make_track("audio", "音频", audio_segments))
    if text_segments:
        tracks.append(make_track("text", "字幕", text_segments))

    timestamp = now_us()
    base_info.update(
        {
            "id": draft_id,
            "name": draft_name,
            "duration": timeline_pos,
            "fps": 30.0,
            "canvas_config": {
                "height": canvas_height,
                "ratio": "original",
                "width": canvas_width,
            },
            "create_time": timestamp,
            "update_time": timestamp,
            "materials": materials,
            "tracks": tracks,
            "static_cover_image_path": "draft_cover.jpg",
        }
    )
    platform = {
        "app_id": 3704,
        "app_source": "lv",
        "app_version": "5.9.0",
        "device_id": "",
        "hard_disk_id": "",
        "mac_address": "",
        "os": "mac",
        "os_version": "",
    }
    base_info["platform"] = platform
    base_info["last_modified_platform"] = platform

    for name in ("draft_info.json", "draft_info.json.bak", "template.tmp", "template-2.tmp", "template.json.bak"):
        dump_json(draft_dir / name, base_info, pretty=True)

    update_meta(draft_dir, draft_id, draft_name, timeline_pos)
    write_timeline_files(draft_dir, draft_id, base_info)
    try_generate_cover(draft_dir, video_dir / f"Scene-001{scene_files[0].suffix.lower()}")

    return draft_dir


def create_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description="Export analysis output to a Jianying draft folder.")
    parser.add_argument("output_dir", help="Analysis output directory containing report.json/scenes/audio.")
    parser.add_argument("--draft-root", default=str(DEFAULT_DRAFT_ROOT), help="Jianying draft root directory.")
    parser.add_argument("--template-dir", default=str(DEFAULT_TEMPLATE_DIR), help="Plain Jianying draft template directory.")
    parser.add_argument("--draft-name", help="New draft folder name. Defaults to a title-based name.")
    return parser


def main() -> None:
    args = create_parser().parse_args()
    draft_dir = build_draft(
        Path(args.output_dir).expanduser().resolve(),
        Path(args.draft_root).expanduser(),
        Path(args.template_dir).expanduser(),
        args.draft_name,
    )
    print(draft_dir)


if __name__ == "__main__":
    main()
